export function satellitePreviewUrl(lat, lng, googleKey) {
  if (googleKey) {
    return `https://maps.googleapis.com/maps/api/staticmap?center=${lat},${lng}&zoom=17&size=560x320&maptype=satellite&key=${googleKey}`;
  }
  const pad = 0.008;
  return `https://server.arcgisonline.com/ArcGIS/rest/services/World_Imagery/MapServer/export?bbox=${lng - pad},${lat - pad},${lng + pad},${lat + pad}&bboxSR=4326&imageSR=4326&size=560,320&format=jpg&f=image`;
}
